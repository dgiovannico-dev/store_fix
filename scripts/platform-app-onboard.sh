#!/usr/bin/env bash
# F4-06 — genera policy OpenBao + checklist Keycloak per una nuova app sulla piattaforma.
# Non parla al cluster: solo artefatti in-repo + istruzioni operatore.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

usage() {
  echo "Usage: $0 <app-id> [--namespace <ns>] [--client-id <oidc-client>]" >&2
  echo "  app-id: slug [a-z0-9-] (es. billing, inventory)" >&2
  echo "Docs: docs/ops/PLATFORM_IAM.md" >&2
  exit 1
}

APP_ID="${1:-}"
[[ -n "$APP_ID" ]] || usage
shift || true

NS=""
CLIENT_ID=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --namespace)
      NS="${2:-}"
      shift 2
      ;;
    --client-id)
      CLIENT_ID="${2:-}"
      shift 2
      ;;
    -h|--help) usage ;;
    *)
      echo "Unknown arg: $1" >&2
      usage
      ;;
  esac
done

if [[ ! "$APP_ID" =~ ^[a-z][a-z0-9-]{1,62}$ ]]; then
  echo "platform-app-onboard FAIL: app-id must match ^[a-z][a-z0-9-]{1,62}$" >&2
  exit 1
fi
if [[ "$APP_ID" == "facilityflow" ]]; then
  echo "platform-app-onboard: facilityflow already has policies/facilityflow-eso.hcl — abort" >&2
  exit 1
fi

NS="${NS:-$APP_ID}"
CLIENT_ID="${CLIENT_ID:-${APP_ID}-app}"
OUT="${ROOT}/deploy/openbao/policies/${APP_ID}-eso.hcl"

if [[ -f "$OUT" ]]; then
  echo "platform-app-onboard FAIL: $OUT already exists" >&2
  exit 1
fi

cat >"$OUT" <<EOF
# OpenBao policy — ${APP_ID} ESO only (generated by platform-app-onboard.sh).
# bao policy write ${APP_ID}-eso deploy/openbao/policies/${APP_ID}-eso.hcl
# KV: secret/apps/${APP_ID}/…

path "secret/data/apps/${APP_ID}/*" {
  capabilities = ["read"]
}

path "secret/metadata/apps/${APP_ID}/*" {
  capabilities = ["read", "list"]
}

path "auth/token/lookup-self" {
  capabilities = ["read"]
}
EOF

echo "Wrote ${OUT}"
echo
echo "=== Checklist Keycloak (realm platform) ==="
echo "1. Admin → Clients → Create clientId=${CLIENT_ID} (confidential, PKCE S256)"
echo "2. Redirect: https://<app-host>/api/auth/callback/keycloak (adatta al broker)"
echo "3. Copia secret → OpenBao (mai git)"
echo
echo "=== Checklist OpenBao ==="
echo "bao policy write ${APP_ID}-eso deploy/openbao/policies/${APP_ID}-eso.hcl"
echo "bao kv put secret/apps/${APP_ID}/runtime @runtime.json"
echo "bao token create -policy=${APP_ID}-eso -ttl=768h -orphan   # oppure k8s role"
echo "kubectl -n ${NS} create secret generic openbao-eso-token --from-literal=token=…"
echo
echo "=== Kubernetes auth (prod) ==="
echo "bao write auth/kubernetes/role/${APP_ID}-eso \\"
echo "  bound_service_account_names='…-eso' \\"
echo "  bound_service_account_namespaces='${NS}' \\"
echo "  policies='${APP_ID}-eso' ttl=1h audience=openbao"
echo
echo "Docs: docs/ops/PLATFORM_IAM.md · docs/ops/VAULT.md · docs/ops/KEYCLOAK.md"
echo "platform-app-onboard OK (${APP_ID})"
