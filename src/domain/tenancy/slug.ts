/** Slug URL-safe da nome workspace (IT retail). */
export function slugifyTenantName(name: string): string {
  const base = name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48);
  return base.length >= 2 ? base : `tenant-${Date.now().toString(36)}`;
}
